#!/usr/bin/env python3
"""Convert Spleen BDF fonts (ASCII 32..126) into a C header of packed MSB-first rows."""
import sys

def parse(path):
    fbb = None; ascent = None; glyphs = {}
    cur = None; in_bitmap = False
    for line in open(path):
        p = line.split()
        if not p: continue
        if p[0] == 'FONTBOUNDINGBOX': fbb = tuple(map(int, p[1:5]))
        elif p[0] == 'FONT_ASCENT': ascent = int(p[1])
        elif p[0] == 'ENCODING': cur = {'enc': int(p[1]), 'rows': []}
        elif p[0] == 'BBX' and cur is not None: cur['bbx'] = tuple(map(int, p[1:5]))
        elif p[0] == 'BITMAP': in_bitmap = True
        elif p[0] == 'ENDCHAR':
            if cur is not None: glyphs[cur['enc']] = cur
            cur = None; in_bitmap = False
        elif in_bitmap and cur is not None: cur['rows'].append(p[0])
    return fbb, ascent, glyphs

def convert(path):
    (fw, fh, fx, fy), ascent, glyphs = parse(path)
    bpr = 1 if fw <= 8 else 2
    out = []
    for code in range(32, 127):
        g = glyphs.get(code)
        cell = [[0]*fw for _ in range(fh)]
        if g:
            bw, bh, xo, yo = g['bbx']
            top = ascent - (yo + bh)
            for gr, hexrow in enumerate(g['rows']):
                nbits = len(hexrow) * 4
                val = int(hexrow, 16)
                for c in range(bw):
                    if (val >> (nbits - 1 - c)) & 1:
                        r = top + gr; col = (xo - fx) + c
                        if 0 <= r < fh and 0 <= col < fw: cell[r][col] = 1
        data = []
        for r in range(fh):
            v = 0
            for c in range(fw): v = (v << 1) | cell[r][c]
            v <<= (bpr*8 - fw)
            data += [(v >> (8*(bpr-1-i))) & 0xFF for i in range(bpr)]
        out.append(data)
    return fw, fh, bpr, out

hdr = ["/* Generated by tools/bdf2c.py from Spleen (BSD-2-Clause, (c) Frederic Cambus). ASCII 32..126, MSB-first rows. */",
       "#pragma once", "#include <stdint.h>", ""]
for name, f in (("6x12","spleen-6x12.bdf"),("8x16","spleen-8x16.bdf"),("12x24","spleen-12x24.bdf")):
    fw, fh, bpr, glyphs = convert(f)
    hdr.append(f"static const uint8_t spleen{name}[95][{fh*bpr}] = {{")
    for i, d in enumerate(glyphs):
        hdr.append("  {" + ",".join(f"0x{b:02x}" for b in d) + "},")
    hdr.append("};\n")
open(sys.argv[1], "w").write("\n".join(hdr))
print("ok")
